"""Text renderings of a snapshot: Markdown report, terminal report, Prometheus."""

import time

ICON = {'error': '\u2716', 'warn': '\u25b2', 'info': '\u25cf'}
PROJECT_URL = 'https://github.com/PhysicalFleet/robot_monitor'


def _b(n):
    if n is None:
        return '-'
    for unit in ('B', 'KB', 'MB', 'GB'):
        if abs(n) < 1024 or unit == 'GB':
            return ('%d %s' % (n, unit)) if unit == 'B' else '%.1f %s' % (n, unit)
        n /= 1024.0


def _hz(x):
    if x is None:
        return '-'
    return '%.3g' % x


def render(snap, fmt='md', color=False):
    if not snap:
        return 'robot_monitor: no data yet\n'
    md = fmt == 'md'
    h = snap.get('host') or {}
    issues = snap.get('issues') or []
    nodes = [n for n in snap.get('nodes', []) if not n.get('hidden') and not n.get('self')]
    topics = [t for t in snap.get('topics', []) if not t.get('hidden') and not t.get('system')]
    errs = sum(1 for i in issues if i['severity'] == 'error')
    warns = sum(1 for i in issues if i['severity'] == 'warn')
    L = []
    title = 'ROS 2 health report \u2014 %s' % h.get('hostname', '?')
    L.append(('# ' if md else '') + title)
    L.append('')
    env = snap.get('env') or {}
    when = time.strftime('%Y-%m-%d %H:%M', time.localtime(snap.get('ts', 0)))
    summary = 'health %s/100  |  %d error(s), %d warning(s)  |  %d nodes, %d topics' % (
        ('**%d**' if md else '%d') % snap.get('score', 0), errs, warns, len(nodes), len(topics))
    L.append((when + '  |  ' + summary) if md else summary)
    envline = 'ROS_DISTRO=%s  RMW=%s  ROS_DOMAIN_ID=%s  host: %s, %s, %d CPUs' % (
        env.get('ROS_DISTRO') or '?', env.get('RMW_IMPLEMENTATION') or 'default',
        env.get('ROS_DOMAIN_ID') or '0', h.get('model') or '?', h.get('os') or '?',
        h.get('ncpu', 0))
    L.append(('`%s`' if md else '%s') % envline)
    L.append('')
    L.append(('## ' if md else '') + 'Issues')
    if not issues:
        L.append('No issues found.')
    for i in issues:
        if md:
            L.append('- **%s %s** \u2014 %s' % (i['severity'].upper(), i['title'], i['detail']))
            if i.get('fix'):
                L.append('  - Fix: %s' % i['fix'])
        else:
            L.append('%s %-5s %s' % (ICON[i['severity']], i['severity'].upper(), i['title']))
            if i.get('detail'):
                L.append('        %s' % i['detail'])
            if i.get('fix'):
                L.append('        fix: %s' % i['fix'])
    L.append('')
    L.append(('## ' if md else '') + 'Nodes')
    rows = [('node', 'pid', 'cpu %', 'memory', 'pubs', 'subs')]
    for n in sorted(nodes, key=lambda n: -(n.get('cpu') or 0)):
        rows.append((n['name'], str(n.get('pid') or ('remote' if n.get('remote') else '?')),
                     '-' if n.get('cpu') is None else '%.1f' % n['cpu'], _b(n.get('rss')),
                     str(len(n['pubs'])), str(len(n['subs']))))
    L.extend(_table(rows, md))
    L.append('')
    L.append(('## ' if md else '') + 'Topics')
    rows = [('topic', 'type', 'hz', 'bandwidth', 'pubs/subs')]
    for t in topics:
        st = t.get('stats') or {}
        rows.append((t['name'], ', '.join(t['types']), _hz(st.get('hz')) if st else '-',
                     (_b(st.get('bw')) + '/s') if st else '-',
                     '%d/%d' % (len(t['pubs']), len(t['subs']))))
    L.extend(_table(rows, md))
    L.append('')
    credit = 'Generated by Robot Monitor %s (%s).' % (snap.get('version', ''), PROJECT_URL)
    L.append(('_%s_' if md else '%s') % credit)
    return '\n'.join(L) + '\n'


def _table(rows, md):
    if md:
        out = ['| ' + ' | '.join(rows[0]) + ' |', '|' + '---|' * len(rows[0])]
        out += ['| ' + ' | '.join(r) + ' |' for r in rows[1:]]
        return out
    widths = [min(60, max(len(r[i]) for r in rows)) for i in range(len(rows[0]))]
    return ['  '.join(c[:60].ljust(w) for c, w in zip(r, widths)).rstrip() for r in rows]


def _esc(s):
    return str(s).replace('\\', '\\\\').replace('"', '\\"').replace('\n', ' ')


def prometheus(snap):
    if not snap:
        return ''
    L = []

    def metric(name, help_, typ='gauge'):
        L.append('# HELP %s %s' % (name, help_))
        L.append('# TYPE %s %s' % (name, typ))

    metric('ros_health_score', 'Overall health score 0-100')
    L.append('ros_health_score %d' % snap.get('score', 0))
    metric('ros_issues', 'Open issues by severity')
    for sev in ('error', 'warn', 'info'):
        L.append('ros_issues{severity="%s"} %d' % (
            sev, sum(1 for i in snap.get('issues', []) if i['severity'] == sev)))
    metric('ros_nodes', 'Nodes in the graph')
    L.append('ros_nodes %d' % len(snap.get('nodes', [])))
    metric('ros_topic_rate_hz', 'Measured topic rate')
    metric_bw = []
    for t in snap.get('topics', []):
        st = t.get('stats')
        if st:
            L.append('ros_topic_rate_hz{topic="%s"} %g' % (_esc(t['name']), st.get('hz') or 0))
            metric_bw.append('ros_topic_bandwidth_bytes{topic="%s"} %g' % (
                _esc(t['name']), st.get('bw') or 0))
    metric('ros_topic_bandwidth_bytes', 'Measured topic bandwidth in bytes/s')
    L.extend(metric_bw)
    metric('ros_node_cpu_percent', 'CPU of the process hosting the node (% of one core)')
    mem = []
    for n in snap.get('nodes', []):
        if n.get('cpu') is not None:
            L.append('ros_node_cpu_percent{node="%s",pid="%s"} %g' % (
                _esc(n['name']), n.get('pid'), n['cpu']))
            mem.append('ros_node_memory_bytes{node="%s",pid="%s"} %d' % (
                _esc(n['name']), n.get('pid'), n.get('rss') or 0))
    metric('ros_node_memory_bytes', 'Resident memory of the process hosting the node')
    L.extend(mem)
    h = snap.get('host') or {}
    if h.get('supported'):
        metric('host_cpu_percent', 'Host CPU use')
        L.append('host_cpu_percent %g' % h.get('cpu', 0))
        metric('host_memory_percent', 'Host memory use')
        L.append('host_memory_percent %g' % h.get('mem_pct', 0))
        metric('host_temperature_celsius', 'Thermal zones')
        for t in h.get('temps') or []:
            L.append('host_temperature_celsius{zone="%s"} %g' % (_esc(t['name']), t['c']))
        th = h.get('throttle') or {}
        if th:
            metric('host_undervoltage', '1 if the board reports under-voltage now')
            L.append('host_undervoltage %d' % int(bool(th.get('undervoltage_now'))))
    return '\n'.join(L) + '\n'
